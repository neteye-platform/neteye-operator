const (
	classisServerComponentID componentID = "classis-server"

	// classisServerName names the Deployment, the Service, the ConfigMap and the
	// policy of the server, and is the host label of its DNS name.
	classisServerName = "classis-server"

	// classisServerDBCredentialsSecretName holds the credentials of the role of
	// the server on a local database, generated by the operator.
	classisServerDBCredentialsSecretName = "classis-db-credentials"

	classisServerAgentPort = 4320
	classisServerAdminPort = 4321
	// classisServerUID is the UID of the non-root user of the distroless image.
	classisServerUID int64 = 65532

	// classisServerEnvPrefix prefixes the environment variables that override the
	// configuration file.
	classisServerEnvPrefix = "CLASSIS_SERVER__"

	// classisServerSecretMode makes mounted Secrets readable by the group of the
	// pod only (fsGroup): the server refuses a secret file readable by others.
	classisServerSecretMode int32 = 0o440

	classisServerConfigVersionAnnotation = "neteye.cloud/classis-server-config-resource-version"
	classisServerConfigFile              = "server.toml"
)

// classisServerSelector selects the pods of the server.
func classisServerSelector() map[string]string {
	return map[string]string{"app.kubernetes.io/name": classisServerName}
}

// classisServerPodLabels are the labels of the pods of the server: its
// selector, and the marks that let the policies of the database and of the
// local object store admit it.
func classisServerPodLabels() map[string]string {
	labels := classisServerSelector()
	labels[tenantDatabaseClientLabel] = "true"
	labels[tenantObjectStorageClientLabel] = "true"
	return labels
}

// classisServerDBCredentials are the Secret keys of the user name and of the
// password of the server on the PostgreSQL of the tenant: the generated Secret
// on a local database, the ones dbConnection names on an external one.
func classisServerDBCredentials(tenant *neteye.NetEyeTenant) (username, password neteye.NetEyeSecretKeySelector) {
	if tenant.Spec.Database.IsLocal() {
		return neteye.NetEyeSecretKeySelector{Name: classisServerDBCredentialsSecretName, Key: corev1.BasicAuthUsernameKey},
			neteye.NetEyeSecretKeySelector{Name: classisServerDBCredentialsSecretName, Key: corev1.BasicAuthPasswordKey}
	}
	if connection := tenant.Spec.ClassisServer.DBConnection; connection != nil && connection.UsernameSecret != nil && connection.PasswordSecret != nil {
		return *connection.UsernameSecret, *connection.PasswordSecret
	}
	return neteye.NetEyeSecretKeySelector{}, neteye.NetEyeSecretKeySelector{}
}

// classisServerCABundle is the CA bundle the server verifies an external
// object store with, when the tenant sets one. A local store is verified
// against the CA of the tenant.
func classisServerCABundle(tenant *neteye.NetEyeTenant) *neteye.NetEyeConfigMapKeySelector {
	if tenant.Spec.ObjectStorage.IsLocal() || tenant.Spec.CABundle == nil {
		return nil
	}
	bundle := tenant.Spec.EffectiveCABundle()
	return &bundle
}

// classisServerFile is the TOML configuration file of the server. The order of
// the fields is the order of the rendered keys and tables.
type classisServerFile struct {
	Listen   string                `toml:"listen"`
	Log      classisServerLog      `toml:"log"`
	REST     classisServerREST     `toml:"rest"`
	Database classisServerDatabase `toml:"database"`
	Blobs    classisServerBlobs    `toml:"blobs"`
	// Packages is nil, and the file has no [packages] section, while no Package
	// Signer is revoked.
	Packages *classisServerPackages `toml:"packages,omitempty"`
}

type classisServerPackages struct {
	RevokedSigners []string `toml:"revoked_signers"`
}

type classisServerLog struct {
	Format string `toml:"format"`
}

type classisServerREST struct {
	Listen string                `toml:"listen"`
	Auth   classisServerRESTAuth `toml:"auth"`
}

type classisServerRESTAuth struct {
	BasicUsersFile string `toml:"basic_users_file"`
}

type classisServerDatabase struct {
	Store    string                `toml:"store"`
	Postgres classisServerPostgres `toml:"postgres"`
}

type classisServerPostgres struct {
	Host         string `toml:"host"`
	Port         int32  `toml:"port"`
	DBName       string `toml:"dbname"`
	PasswordFile string `toml:"password_file"`
	CAFile       string `toml:"ca_file"`
	TLS          bool   `toml:"tls"`
}

type classisServerBlobs struct {
	Store string          `toml:"store"`
	S3    classisServerS3 `toml:"s3"`
}

type classisServerS3 struct {
	Endpoint            string `toml:"endpoint"`
	Bucket              string `toml:"bucket"`
	Region              string `toml:"region"`
	Prefix              string `toml:"prefix"`
	SecretAccessKeyFile string `toml:"secret_access_key_file,omitempty"`
	CAFile              string `toml:"ca_file,omitempty"`
}

// classisServerFileOf builds the configuration of the server. Secrets are
// paths of the files the Deployment mounts; the database user and the S3
// access key are the values that come from the environment.
//
// The server speaks plain HTTP: a reverse proxy in front of it ends TLS. The
// server admits an agent only by the bearer token it issued when the host
// enrolled with the key of its Space, and refuses an [agents] section, so the
// file has none.
//
// revokedSigners are the Package Signers the server refuses; the file has a
// [packages] section only when there is one.
func classisServerFileOf(tenant *neteye.NetEyeTenant, revokedSigners []string) classisServerFile {
	spec := tenant.Spec.ClassisServer
	database := tenantDatabaseEndpointOf(tenant)
	storage := tenantObjectStorageEndpointOf(tenant)
	logFormat := spec.LogFormat
	if logFormat == "" {
		logFormat = "json"
	}
	s3 := classisServerS3{Endpoint: storage.Endpoint, Bucket: storage.Bucket, Region: storage.Region, Prefix: spec.EffectiveObjectStoragePrefix()}
	if storage.CredentialsSecret != "" {
		s3.SecretAccessKeyFile = classisServerMount("s3-credentials") + "/secret-access-key"
	}
	if storage.CASecret != nil {
		s3.CAFile = classisServerMount("s3-ca") + "/ca.crt"
	} else if ca := classisServerCABundle(tenant); ca != nil {
		s3.CAFile = classisServerMount("ca-bundle") + "/" + ca.Key
	}
	var packages *classisServerPackages
	if len(revokedSigners) > 0 {
		packages = &classisServerPackages{RevokedSigners: revokedSigners}
	}
	return classisServerFile{
		Listen: fmt.Sprintf("0.0.0.0:%d", classisServerAgentPort),
		Log:    classisServerLog{Format: logFormat},
		REST: classisServerREST{
			Listen: fmt.Sprintf("0.0.0.0:%d", classisServerAdminPort),
			Auth:   classisServerRESTAuth{BasicUsersFile: classisServerMount("admin-users") + "/basic-users"},
		},
		Database: classisServerDatabase{Store: "postgres", Postgres: classisServerPostgres{
			Host:         database.Host,
			Port:         database.Port,
			DBName:       spec.EffectiveDBName(),
			PasswordFile: classisServerMount("db-password") + "/password",
			CAFile:       classisServerMount("db-ca") + "/ca.crt",
			TLS:          true,
		}},
		Blobs:    classisServerBlobs{Store: "s3", S3: s3},
		Packages: packages,
	}
}

// classisServerConfig renders the configuration of the server as TOML. The
// encoder quotes and escapes every value, so no value of the spec can change
// the structure of the file.
func classisServerConfig(tenant *neteye.NetEyeTenant, revokedSigners []string) (string, error) {
	var b strings.Builder
	encoder := toml.NewEncoder(&b)
	encoder.Indent = ""
	if err := encoder.Encode(classisServerFileOf(tenant, revokedSigners)); err != nil {
		return "", fmt.Errorf("render the Classis Server configuration: %w", err)
	}
	return b.String(), nil
}

// revokedPackageSigners returns the Package Signers that the Classis Server of
// every tenant refuses: the union of the lists of the NetEye resources, sorted,
// so that an order change does not restart the servers.
//
// A Package Signer signs for the whole product, so when its key is exposed the
// server of every tenant must refuse it. The list therefore lives on the NetEye
// resource and not on each tenant, where an emergency would mean patching every
// tenant, nor in the release data, where a revocation would wait for an
// operator release. One change of the NetEye resource reaches every tenant at
// once: the operator renders the list into the configuration of each server,
// and the changed ConfigMap restarts it (the server reads the list at start).
func (r *NetEyeTenantReconciler) revokedPackageSigners(ctx context.Context) ([]string, error) {
	list := &neteye.NetEyeList{}
	if err := r.List(ctx, list); err != nil {
		return nil, fmt.Errorf("list NetEye resources: %w", err)
	}
	var signers []string
	for i := range list.Items {
		signers = append(signers, list.Items[i].Spec.EffectiveRevokedPackageSigners()...)
	}
	slices.Sort(signers)
	return slices.Compact(signers), nil
}

func classisServerMount(volume string) string { return "/etc/classis/" + volume }

func secretVolume(name, secretName string) corev1.Volume {
	return corev1.Volume{Name: name, VolumeSource: corev1.VolumeSource{Secret: &corev1.SecretVolumeSource{SecretName: secretName, DefaultMode: ptr.To(classisServerSecretMode)}}}
}

// secretKeyVolume projects one key of a Secret as the file path, so that the
// pod sees nothing else of the Secret.
func secretKeyVolume(name string, key neteye.NetEyeSecretKeySelector, path string) corev1.Volume {
	return corev1.Volume{Name: name, VolumeSource: corev1.VolumeSource{Secret: &corev1.SecretVolumeSource{SecretName: key.Name, DefaultMode: ptr.To(classisServerSecretMode), Items: []corev1.KeyToPath{{Key: key.Key, Path: path}}}}}
}

// classisServerDeployment builds the Deployment of the server. One replica and
// the Recreate strategy: the database lock lets only one server run, so the old
// pod stops before the new one starts. The root filesystem is read-only and the
// only writable volume is an emptyDir for /tmp: the server keeps its records in
// PostgreSQL and its artifacts in S3.
func classisServerDeployment(tenant *neteye.NetEyeTenant, image, configVersion, secretsVersions string) *appsv1.Deployment {
	spec := tenant.Spec.ClassisServer
	database := tenantDatabaseEndpointOf(tenant)
	storage := tenantObjectStorageEndpointOf(tenant)
	username, password := classisServerDBCredentials(tenant)
	labels := classisServerSelector()

	volumes := []corev1.Volume{
		{Name: "config", VolumeSource: corev1.VolumeSource{ConfigMap: &corev1.ConfigMapVolumeSource{LocalObjectReference: corev1.LocalObjectReference{Name: classisServerName}}}},
		{Name: "tmp", VolumeSource: corev1.VolumeSource{EmptyDir: &corev1.EmptyDirVolumeSource{}}},
		secretVolume("admin-users", classisServerAdminUsersSecret(spec)),
		secretKeyVolume("db-password", password, "password"),
		secretKeyVolume("db-ca", database.CASecret, "ca.crt"),
	}
	env := []corev1.EnvVar{
		{Name: "RUST_LOG", Value: spec.LogLevel},
		secretEnv(classisServerEnvPrefix+"DATABASE__POSTGRES__USER", username.Name, username.Key),
	}
	if storage.CredentialsSecret != "" {
		volumes = append(volumes, secretVolume("s3-credentials", storage.CredentialsSecret))
		env = append(env, secretEnv(classisServerEnvPrefix+"BLOBS__S3__ACCESS_KEY_ID", storage.CredentialsSecret, "access-key-id"))
	}
	if storage.CASecret != nil {
		volumes = append(volumes, secretKeyVolume("s3-ca", *storage.CASecret, "ca.crt"))
	} else if ca := classisServerCABundle(tenant); ca != nil {
		volumes = append(volumes, corev1.Volume{Name: "ca-bundle", VolumeSource: corev1.VolumeSource{ConfigMap: &corev1.ConfigMapVolumeSource{LocalObjectReference: corev1.LocalObjectReference{Name: ca.Name}, Items: []corev1.KeyToPath{{Key: ca.Key, Path: ca.Key}}}}})
	}
	mounts := []corev1.VolumeMount{
		{Name: "config", MountPath: "/etc/classis/config", ReadOnly: true},
		{Name: "tmp", MountPath: "/tmp"},
	}
	for _, volume := range volumes[2:] {
		mounts = append(mounts, corev1.VolumeMount{Name: volume.Name, MountPath: classisServerMount(volume.Name), ReadOnly: true})
	}

	// /livez and /readyz are served on the operator plane, outside its Basic
	// authentication, over plain HTTP. The startup probe allows 300 s (60 times
	// 5 s): at startup the server retries PostgreSQL and S3 for up to 180 s, and
	// the kubelet must not kill it while it does.
	probe := func(path string) *corev1.Probe {
		return &corev1.Probe{ProbeHandler: corev1.ProbeHandler{HTTPGet: &corev1.HTTPGetAction{Path: path, Scheme: corev1.URISchemeHTTP, Port: intstr.FromString("admin")}}, PeriodSeconds: 10, TimeoutSeconds: 2, FailureThreshold: 3}
	}
	startup := probe("/readyz")
	startup.PeriodSeconds, startup.FailureThreshold = 5, 60

	return &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: classisServerName, Namespace: tenant.Namespace, Labels: labels},
		Spec: appsv1.DeploymentSpec{
			Replicas: ptr.To(int32(1)),
			Strategy: appsv1.DeploymentStrategy{Type: appsv1.RecreateDeploymentStrategyType},
			Selector: &metav1.LabelSelector{MatchLabels: labels},
			Template: corev1.PodTemplateSpec{
				ObjectMeta: metav1.ObjectMeta{Labels: classisServerPodLabels(), Annotations: map[string]string{classisServerConfigVersionAnnotation: configVersion, classisServerSecretsVersionsAnnotation: secretsVersions}},
				Spec: corev1.PodSpec{
					AutomountServiceAccountToken:  ptr.To(false),
					TerminationGracePeriodSeconds: ptr.To(int64(30)),
					SecurityContext:               nonRootPodSecurityContext(classisServerUID),
					Containers: []corev1.Container{{
						Name:  classisServerName,
						Image: image,
						Args:  []string{"--config", "/etc/classis/config/" + classisServerConfigFile},
						Ports: []corev1.ContainerPort{
							{Name: "agent", ContainerPort: classisServerAgentPort},
							{Name: "admin", ContainerPort: classisServerAdminPort},
						},
						Env:             env,
						VolumeMounts:    mounts,
						LivenessProbe:   probe("/livez"),
						ReadinessProbe:  probe("/readyz"),
						StartupProbe:    startup,
						SecurityContext: restrictedContainerSecurityContext(),
					}},
					Volumes: volumes,
				},
			},
		},
	}
}

// classisServerService exposes the two planes inside the cluster. The proxies of
// the PCS nodes publish the agent plane; the operator plane stays internal, and
// the network policy decides who reaches it.
func classisServerService(tenant *neteye.NetEyeTenant) *corev1.Service {
	return &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{Name: classisServerName, Namespace: tenant.Namespace, Labels: classisServerSelector()},
		Spec: corev1.ServiceSpec{
			Type:     corev1.ServiceTypeClusterIP,
			Selector: classisServerSelector(),
			Ports: []corev1.ServicePort{
				{Name: "agent", Port: classisServerAgentPort, TargetPort: intstr.FromString("agent"), Protocol: corev1.ProtocolTCP},
				{Name: "admin", Port: classisServerAdminPort, TargetPort: intstr.FromString("admin"), Protocol: corev1.ProtocolTCP},
			},
		},
	}
}

func cidrPeers(cidrs []string) []any {
	peers := make([]any, 0, len(cidrs))
	for _, cidr := range cidrs {
		peers = append(peers, map[string]any{"ipBlock": map[string]any{"cidr": cidr}})
	}
	return peers
}

func podSelector(labels map[string]string) map[string]any {
	match := map[string]any{}
	for k, v := range labels {
		match[k] = v
	}
	return map[string]any{"matchLabels": match}
}

func namespaceNamed(name string) map[string]any {
	return map[string]any{"matchLabels": map[string]any{"kubernetes.io/metadata.name": name}}
}

var dnsEgress = map[string]any{
	"to":    []any{map[string]any{"namespaceSelector": namespaceNamed("kube-system"), "podSelector": podSelector(map[string]string{"k8s-app": "kube-dns"})}},
	"ports": append(resources.NetworkPolicyPorts("UDP", 53), resources.NetworkPolicyPorts("TCP", 53)...),
}

// anyPeerPorts is a rule that names no peer: the ports are open to any source
// or destination. A native policy cannot name the Kubernetes API, the nodes or
// a service outside the cluster, so these rules are widened to the ports, as in
// the policies of the other components.
func anyPeerPorts(ports []any) map[string]any {
	return map[string]any{"ports": ports}
}

// s3Port is the port of the S3 endpoint, 443 when the URL names none.
func s3Port(endpoint string) int64 {
	parsed, err := url.Parse(endpoint)
	if err != nil {
		return 443
	}
	port, err := strconv.ParseInt(parsed.Port(), 10, 32)
	if err != nil || port <= 0 {
		return 443
	}
	return port
}

// classisServerNetworkPolicySpec opens, over the default deny of the tenant, the
// planes of the server, its way to PostgreSQL, to the object store and to DNS.
//
// The agent plane (4320) is open to any source: a native policy cannot select
// the nodes of the PCS proxy, and the server admits an agent only by the bearer
// token it issued, on /v1/opamp and on the package download alike. The server
// trusts X-Forwarded-For from any source, so a peer that bypasses the proxy can
// choose the address its admission failures and its rate are counted under: it
// can evade the throttle, not present itself as another host.
//
// The operator plane (4321) is open only to adminIngressCIDRs, and closed when
// they are empty. The policy lists no rule for the kubelet: the kubelet probes
// 4321 from the node, and Cilium admits the traffic of the local node to its
// pods whatever the policies say, so the probes pass with the plane closed.
// The egress to an external database and to an external object store is open to
// any destination on their ports, because a native policy cannot name a
// service outside the cluster.
func classisServerNetworkPolicySpec(tenant *neteye.NetEyeTenant) map[string]any {
	network := tenant.Spec.ClassisServer.Network
	ingress := []any{anyPeerPorts(resources.NetworkPolicyPorts("TCP", classisServerAgentPort))}
	if len(network.AdminIngressCIDRs) > 0 {
		ingress = append(ingress, map[string]any{"from": cidrPeers(network.AdminIngressCIDRs), "ports": resources.NetworkPolicyPorts("TCP", classisServerAdminPort)})
	}
	database := tenantDatabaseEndpointOf(tenant)
	storage := tenantObjectStorageEndpointOf(tenant)
	egress := []any{dnsEgress}
	var anyPorts []int64
	if database.Local {
		egress = append(egress, map[string]any{
			"to":    []any{map[string]any{"podSelector": podSelector(map[string]string{"cnpg.io/cluster": tenantDatabaseName})}},
			"ports": resources.NetworkPolicyPorts("TCP", int64(database.Port)),
		})
	} else {
		anyPorts = append(anyPorts, int64(database.Port))
	}
	if storage.Local {
		egress = append(egress, tenantObjectStorageEgress())
	} else if port := s3Port(storage.Endpoint); len(anyPorts) == 0 || anyPorts[0] != port {
		anyPorts = append(anyPorts, port)
	}
	if len(anyPorts) > 0 {
		egress = append(egress, anyPeerPorts(resources.NetworkPolicyPorts("TCP", anyPorts...)))
	}
	return map[string]any{
		"podSelector": podSelector(classisServerSelector()),
		"policyTypes": []any{"Ingress", "Egress"},
		"ingress":     ingress,
		"egress":      egress,
	}
}

// classisServerComponents returns the lifecycle nodes and operations of the
// server, or none when the tenant has no server. An enabled server comes after
// the database and the object store of the tenant. A disabled server only
// deletes its Deployment, so it waits for the namespace alone: a store that
// never becomes ready must not keep a disabled server running.
func (r *NetEyeTenantReconciler) classisServerComponents(ctx context.Context, tenant *neteye.NetEyeTenant) ([]lifecycleNode, map[componentID]componentOperation) {
	if tenant.Spec.ClassisServer == nil {
		return nil, nil
	}
	dependencies := []componentID{tenantNamespaceComponentID}
	if tenant.Spec.ClassisServer.Enabled && tenant.Spec.Database != nil {
		dependencies = append(dependencies, tenantDatabaseComponentID)
	}
	if tenant.Spec.ClassisServer.Enabled && tenant.Spec.ObjectStorage != nil {
		dependencies = append(dependencies, tenantObjectStorageComponentID)
	}
	return []lifecycleNode{{ID: classisServerComponentID, Dependencies: dependencies}},
		map[componentID]componentOperation{classisServerComponentID: func() (componentResult, error) { return r.reconcileClassisServer(ctx, tenant) }}
}

// reconcileClassisServer applies the configuration, the Service, the network
// policy and the Deployment of the server, then reports the Deployment state.
// A disabled server loses its Deployment and nothing else.
func (r *NetEyeTenantReconciler) reconcileClassisServer(ctx context.Context, tenant *neteye.NetEyeTenant) (componentResult, error) {
	spec := tenant.Spec.ClassisServer
	if !spec.Enabled {
		deployment := &appsv1.Deployment{ObjectMeta: metav1.ObjectMeta{Name: classisServerName, Namespace: tenant.Namespace}}
		if err := r.Delete(ctx, deployment); err != nil && !apierrors.IsNotFound(err) {
			return degradedResult(classisServerComponentID, "DeploymentFailed", err.Error(), r.failureRequeue(), err)
		}
		return readyResult(classisServerComponentID, "Disabled", "The Classis Server is disabled")
	}
	if errors := neteye.ValidateClassisServer(tenant); len(errors) > 0 {
		err := errors.ToAggregate()
		return degradedResult(classisServerComponentID, "InvalidSpec", err.Error(), r.failureRequeue(), err)
	}
	owner := resources.OwnerReference(neteye.GroupVersion.String(), "NetEyeTenant", tenant)
	images, err := r.tenantImages(ctx)
	if err != nil {
		return r.imagesResult(classisServerComponentID, err)
	}
	if err := r.ensureGeneratedAdminSecrets(ctx, tenant); err != nil {
		return degradedResult(classisServerComponentID, "AdminSecretFailed", err.Error(), r.failureRequeue(), err)
	}
	secrets := classisServerSecretNames(tenant)
	if missing, err := r.missingSecrets(ctx, tenant.Namespace, secrets); err != nil {
		return degradedResult(classisServerComponentID, "SecretCheckFailed", err.Error(), r.failureRequeue(), err)
	} else if len(missing) > 0 {
		return progressingResult(classisServerComponentID, "WaitingForSecrets", "waiting for Secrets: "+strings.Join(missing, ", "), r.progressingRequeue())
	}

	revokedSigners, err := r.revokedPackageSigners(ctx)
	if err != nil {
		return degradedResult(classisServerComponentID, "ConfigFailed", err.Error(), r.failureRequeue(), err)
	}
	config, err := classisServerConfig(tenant, revokedSigners)
	if err != nil {
		return degradedResult(classisServerComponentID, "ConfigFailed", err.Error(), r.failureRequeue(), err)
	}
	configVersion, err := resources.EnsureConfigMap(ctx, r.Client, tenant.Namespace, classisServerName, map[string]string{classisServerConfigFile: config}, owner)
	if err != nil {
		return degradedResult(classisServerComponentID, "ConfigFailed", err.Error(), r.failureRequeue(), err)
	}
	if err := resources.EnsureService(ctx, r.Client, classisServerService(tenant), owner); err != nil {
		return degradedResult(classisServerComponentID, "ServiceFailed", err.Error(), r.failureRequeue(), err)
	}
	if err := resources.EnsureNetworkPolicy(ctx, r.Client, tenant.Namespace, classisServerName, classisServerNetworkPolicySpec(tenant), owner); err != nil {
		return degradedResult(classisServerComponentID, "NetworkPolicyFailed", err.Error(), r.failureRequeue(), err)
	}
	secretsVersions, err := r.secretVersions(ctx, tenant.Namespace, secrets, classisServerCABundle(tenant))
	if err != nil {
		return degradedResult(classisServerComponentID, "SecretCheckFailed", err.Error(), r.failureRequeue(), err)
	}
	if err := resources.EnsureDeployment(ctx, r.Client, classisServerDeployment(tenant, images.ClassisServerImage, configVersion, secretsVersions), owner); err != nil {
		return degradedResult(classisServerComponentID, "DeploymentFailed", err.Error(), r.failureRequeue(), err)
	}
	ready, message, err := resources.IsDeploymentReady(ctx, r.Client, tenant.Namespace, classisServerName)
	if err != nil {
		return degradedResult(classisServerComponentID, "DeploymentFailed", err.Error(), r.failureRequeue(), err)
	}
	if !ready {
		return progressingResult(classisServerComponentID, "WaitingForDeployment", message, r.progressingRequeue())
	}
	return readyResult(classisServerComponentID, "Available", "The Classis Server is ready")
}

// classisServerSecretNames names every Secret the pod of the server mounts or
// reads its environment from.
func classisServerSecretNames(tenant *neteye.NetEyeTenant) []string {
	username, password := classisServerDBCredentials(tenant)
	storage := tenantObjectStorageEndpointOf(tenant)
	names := []string{classisServerAdminUsersSecret(tenant.Spec.ClassisServer), username.Name, password.Name, tenantDatabaseEndpointOf(tenant).CASecret.Name, storage.CredentialsSecret}
	if storage.CASecret != nil {
		names = append(names, storage.CASecret.Name)
	}
	return names
}

// missingSecrets names the Secrets among names that do not exist yet, so that
// the pod is not created only to stay in ContainerCreating.
func (r *NetEyeTenantReconciler) missingSecrets(ctx context.Context, namespace string, names []string) ([]string, error) {
	seen := map[string]struct{}{}
	var missing []string
	for _, name := range names {
		if _, done := seen[name]; done || name == "" {
			continue
		}
		seen[name] = struct{}{}
		err := r.Get(ctx, types.NamespacedName{Namespace: namespace, Name: name}, &corev1.Secret{})
		switch {
		case apierrors.IsNotFound(err):
			missing = append(missing, name)
		case err != nil:
			return nil, fmt.Errorf("get Secret %q: %w", name, err)
		}
	}
	sort.Strings(missing)
	return missing, nil
}
